//! [`Alert`]: a query evaluated over each new slot range, whose rows are
//! posted to a webhook.
//!
//! # SQL
//!
//! Alert SQL goes through the saved-query template checks (single statement,
//! size cap, bare placeholders; see [`super::saved_query`]) with two
//! differences. The only placeholders allowed are `{{from_slot}}` and
//! `{{to_slot}}`, and **both** must appear. An alert that ignored
//! `from_slot` would re-read rows it already fired on, and fire on them
//! again, every batch.
//!
//! The range is inclusive on both ends:
//!
//! ```text
//! SELECT * FROM transfers WHERE slot BETWEEN {{from_slot}} AND {{to_slot}} AND amount > 1000000
//! ```
//!
//! # Progress
//!
//! `last_evaluated_slot` is the highest slot the alert has been evaluated
//! through, or `None` before its first evaluation and after re-enabling. The
//! next range is [`Alert::next_range`]. Progress only moves through
//! [`super::Registry::advance_progress`], in the transaction that enqueues
//! the range's delivery.

use serde::{Deserialize, Serialize};
use url::Url;

use super::RegistryError;
use super::saved_query::{validate_name, validate_template};

pub const FROM_SLOT: &str = "from_slot";
pub const TO_SLOT: &str = "to_slot";

/// Webhook URL schemes an alert may use.
pub const WEBHOOK_URL_SCHEMES: [&str; 2] = ["http", "https"];
pub const MAX_WEBHOOK_URL_LEN: usize = 2048;
/// Shortest signing secret accepted: below this an HMAC is guessable.
pub const MIN_SECRET_LEN: usize = 16;
pub const MAX_SECRET_LEN: usize = 512;

/// An alert as stored in the registry.
///
/// `secret` is never serialized (so an API response cannot leak it) and is
/// redacted from `Debug`. It is stored in plaintext because SQLite has no
/// column encryption and the dispatcher needs the raw value to sign.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Alert {
    /// UUID v4, generated by the registry.
    pub id: String,
    pub name: String,
    pub sql: String,
    pub webhook_url: String,
    #[serde(skip_serializing, default)]
    pub secret: String,
    /// Evaluate a range only once all of it is finalized.
    pub wait_for_final: bool,
    pub enabled: bool,
    pub last_evaluated_slot: Option<u64>,
    /// Unix seconds.
    pub created_at: i64,
    /// Unix seconds.
    pub updated_at: i64,
}

impl std::fmt::Debug for Alert {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Alert")
            .field("id", &self.id)
            .field("name", &self.name)
            .field("sql", &self.sql)
            .field("webhook_url", &self.webhook_url)
            .field("secret", &"<redacted>")
            .field("wait_for_final", &self.wait_for_final)
            .field("enabled", &self.enabled)
            .field("last_evaluated_slot", &self.last_evaluated_slot)
            .field("created_at", &self.created_at)
            .field("updated_at", &self.updated_at)
            .finish()
    }
}

impl Alert {
    /// The SQL with both slots rendered as plain integers. The caller passes
    /// `from_slot <= to_slot`, as [`Alert::next_range`] returns them.
    pub fn bind_range(&self, from_slot: u64, to_slot: u64) -> String {
        debug_assert!(from_slot <= to_slot, "empty range {from_slot}..={to_slot}");
        // Stored SQL was validated on the way in, so it parses and names
        // only the two slots.
        validate_template("sql", &self.sql)
            .and_then(|template| {
                template.render(|name| Ok(if name == FROM_SLOT { from_slot } else { to_slot }.to_string()))
            })
            .expect("stored alert SQL is a valid template")
    }

    /// The inclusive range to evaluate once the change log has reached
    /// `to_slot`, given that the current batch starts at `batch_from_slot`.
    /// The range resumes after `last_evaluated_slot`, or starts at
    /// `batch_from_slot` when there is no progress. `None` when nothing new
    /// is in range.
    pub fn next_range(&self, batch_from_slot: u64, to_slot: u64) -> Option<(u64, u64)> {
        let from = match self.last_evaluated_slot {
            Some(last) => last.checked_add(1)?,
            None => batch_from_slot,
        };
        (from <= to_slot).then_some((from, to_slot))
    }
}

/// What a client submits to create an alert. The registry generates the
/// id, starts it enabled and with no progress.
#[derive(Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct NewAlert {
    pub name: String,
    pub sql: String,
    pub webhook_url: String,
    pub secret: String,
    #[serde(default)]
    pub wait_for_final: bool,
}

impl std::fmt::Debug for NewAlert {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("NewAlert")
            .field("name", &self.name)
            .field("sql", &self.sql)
            .field("webhook_url", &self.webhook_url)
            .field("secret", &"<redacted>")
            .field("wait_for_final", &self.wait_for_final)
            .finish()
    }
}

impl NewAlert {
    pub fn validate(&self) -> Result<(), RegistryError> {
        validate_name("name", &self.name)?;
        validate_alert_sql(&self.sql)?;
        validate_webhook_url(&self.webhook_url)?;
        validate_secret(&self.secret)
    }
}

/// A partial update: each `Some` field replaces the stored one.
#[derive(Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct AlertUpdate {
    pub name: Option<String>,
    pub sql: Option<String>,
    pub webhook_url: Option<String>,
    pub secret: Option<String>,
    pub wait_for_final: Option<bool>,
}

impl std::fmt::Debug for AlertUpdate {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("AlertUpdate")
            .field("name", &self.name)
            .field("sql", &self.sql)
            .field("webhook_url", &self.webhook_url)
            .field("secret", &self.secret.as_ref().map(|_| "<redacted>"))
            .field("wait_for_final", &self.wait_for_final)
            .finish()
    }
}

impl AlertUpdate {
    /// Validate each set field and write it into `alert`. On error `alert`
    /// may be partly updated; the registry discards it.
    pub(crate) fn apply_to(self, alert: &mut Alert) -> Result<(), RegistryError> {
        if let Some(name) = self.name {
            validate_name("name", &name)?;
            alert.name = name;
        }
        if let Some(sql) = self.sql {
            validate_alert_sql(&sql)?;
            alert.sql = sql;
        }
        if let Some(url) = self.webhook_url {
            validate_webhook_url(&url)?;
            alert.webhook_url = url;
        }
        if let Some(secret) = self.secret {
            validate_secret(&secret)?;
            alert.secret = secret;
        }
        if let Some(wait) = self.wait_for_final {
            alert.wait_for_final = wait;
        }
        Ok(())
    }
}

pub fn validate_alert_sql(sql: &str) -> Result<(), RegistryError> {
    let template = validate_template("sql", sql)?;
    let names = template.placeholder_names();
    let mut unknown: Vec<_> = names.iter().filter(|n| **n != FROM_SLOT && **n != TO_SLOT).collect();
    unknown.sort();
    if let Some(name) = unknown.first() {
        return Err(RegistryError::invalid(
            "sql",
            format!("placeholder {{{{{name}}}}} is not allowed; alerts use only {{{{from_slot}}}} and {{{{to_slot}}}}"),
        ));
    }
    for required in [FROM_SLOT, TO_SLOT] {
        if !names.contains(required) {
            return Err(RegistryError::invalid(
                "sql",
                format!("must use {{{{{required}}}}}; without both bounds every batch re-reads rows it already fired on"),
            ));
        }
    }
    Ok(())
}

/// `http(s)://host...`, with no credentials and no fragment. Error messages
/// never echo the URL, which may embed a token.
pub fn validate_webhook_url(raw: &str) -> Result<(), RegistryError> {
    let invalid = |reason: &str| RegistryError::invalid("webhook_url", reason);
    if raw.len() > MAX_WEBHOOK_URL_LEN {
        return Err(invalid("is too long"));
    }
    let url = Url::parse(raw).map_err(|_| invalid("is not a valid URL"))?;
    if !WEBHOOK_URL_SCHEMES.contains(&url.scheme()) {
        return Err(invalid("must use http or https"));
    }
    if url.host_str().is_none_or(str::is_empty) {
        return Err(invalid("must name a host"));
    }
    if !url.username().is_empty() || url.password().is_some() {
        return Err(invalid("must not embed credentials; the delivery signature authenticates FORGE"));
    }
    if url.fragment().is_some() {
        return Err(invalid("must not have a fragment"));
    }
    if url.port() == Some(0) {
        return Err(invalid("port 0 is not allowed"));
    }
    Ok(())
}

fn validate_secret(secret: &str) -> Result<(), RegistryError> {
    let len = secret.len();
    if !(MIN_SECRET_LEN..=MAX_SECRET_LEN).contains(&len) {
        return Err(RegistryError::invalid(
            "secret",
            format!("must be {MIN_SECRET_LEN} to {MAX_SECRET_LEN} bytes, got {len}"),
        ));
    }
    if secret.trim() != secret || secret.chars().any(char::is_control) {
        return Err(RegistryError::invalid("secret", "must not have surrounding whitespace or control characters"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    const SQL: &str = "SELECT * FROM t WHERE slot BETWEEN {{from_slot}} AND {{to_slot}}";

    fn alert(sql: &str, last: Option<u64>) -> Alert {
        Alert {
            id: "id".into(),
            name: "a".into(),
            sql: sql.into(),
            webhook_url: "https://hooks.example.com/x".into(),
            secret: "0123456789abcdef".into(),
            wait_for_final: false,
            enabled: true,
            last_evaluated_slot: last,
            created_at: 0,
            updated_at: 0,
        }
    }

    #[test]
    fn alert_sql_needs_both_slots_and_nothing_else() {
        assert!(validate_alert_sql(SQL).is_ok());
        assert!(validate_alert_sql("SELECT {{to_slot}}, {{from_slot}}, {{to_slot}}").is_ok());
        for bad in [
            "SELECT * FROM t WHERE slot <= {{to_slot}}",
            "SELECT * FROM t WHERE slot >= {{from_slot}}",
            "SELECT 1",
            "SELECT {{from_slot}} {{to_slot}} {{wallet}}",
            "SELECT '{{from_slot}}', {{to_slot}}",
            "SELECT {{from_slot}}, {{to_slot}}; SELECT 1",
        ] {
            assert!(validate_alert_sql(bad).is_err(), "{bad}");
        }
    }

    #[test]
    fn bind_range_renders_plain_integers() {
        assert_eq!(
            alert(SQL, None).bind_range(10, u64::MAX),
            "SELECT * FROM t WHERE slot BETWEEN 10 AND 18446744073709551615"
        );
    }

    #[test]
    fn next_range_resumes_after_progress() {
        assert_eq!(alert(SQL, None).next_range(5, 9), Some((5, 9)));
        assert_eq!(alert(SQL, Some(6)).next_range(5, 9), Some((7, 9)));
        assert_eq!(alert(SQL, Some(9)).next_range(5, 9), None);
        assert_eq!(alert(SQL, Some(u64::MAX)).next_range(0, u64::MAX), None);
    }

    #[test]
    fn webhook_urls() {
        for ok in ["http://h", "https://hooks.example.com:8443/a?b=c", "http://127.0.0.1:9000/x", "http://[::1]/"] {
            assert!(validate_webhook_url(ok).is_ok(), "{ok}");
        }
        for bad in [
            "hooks.example.com",
            "ftp://h",
            "file:///tmp/x",
            "http://",
            "http://u@h",
            "http://u:p@h",
            "http://:p@h",
            "http://h#x",
            "http://h:0",
            "mailto:a@b",
        ] {
            assert!(validate_webhook_url(bad).is_err(), "{bad}");
        }
        let err = validate_webhook_url("ftp://admin:hunter2@h").unwrap_err();
        assert!(!err.to_string().contains("hunter2"), "{err}");
    }

    #[test]
    fn secrets() {
        assert!(validate_secret(&"s".repeat(MIN_SECRET_LEN)).is_ok());
        assert!(validate_secret(&"s".repeat(MIN_SECRET_LEN - 1)).is_err());
        assert!(validate_secret(&"s".repeat(MAX_SECRET_LEN + 1)).is_err());
        assert!(validate_secret(" 0123456789abcdef").is_err());
        assert!(validate_secret("0123456789abcdef\n").is_err());
    }

    #[test]
    fn secret_is_never_serialized_or_debug_printed() {
        let a = alert(SQL, None);
        assert!(!serde_json::to_string(&a).unwrap().contains(&a.secret));
        assert!(!format!("{a:?}").contains(&a.secret));
        let update = AlertUpdate {
            secret: Some("topsecretvalue!!".into()),
            ..AlertUpdate::default()
        };
        assert!(!format!("{update:?}").contains("topsecret"));
    }

    #[test]
    fn update_validates_each_field() {
        let mut a = alert(SQL, Some(3));
        let bad = AlertUpdate {
            sql: Some("SELECT {{to_slot}}".into()),
            ..AlertUpdate::default()
        };
        assert!(bad.apply_to(&mut a.clone()).is_err());
        AlertUpdate {
            wait_for_final: Some(true),
            ..AlertUpdate::default()
        }
        .apply_to(&mut a)
        .unwrap();
        assert!(a.wait_for_final);
        assert_eq!(a.last_evaluated_slot, Some(3));
    }
}
